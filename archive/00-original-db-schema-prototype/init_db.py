def main():
    """主初始化流程"""
    print("=" * 70)
    print("飲食管理系統 - 數據庫初始化")
    print("=" * 70)
    
    # 檢查數據庫是否已存在
    if DB_PATH.exists():
        print(f"⚠ 數據庫已存在: {DB_PATH}")
        response = input("是否要刪除並重新創建? (y/n): ").strip().lower()
        if response == 'y':
            DB_PATH.unlink()
            print("✓ 已刪除舊數據庫")
        else:
            print("✗ 已取消初始化")
            return
    
    # 創建數據庫和加載架構
    conn = create_database()
    load_schema(conn)
    record_schema_version(conn)
    
    # 加載種子數據
    print("\n加載種子數據...")
    load_purchase_locations(conn)
    load_ingredients(conn)
    load_exercise_items(conn)
    load_yoga_stretch_items(conn)
    initialize_ingredient_stock(conn)
    
    # 關閉連接
    conn.close()
    
    print("\n" + "=" * 70)
    print("✓ 數據庫初始化完成！")
    print(f"  數據庫文件: {DB_PATH.absolute()}")
    print("  已加載:")
    print(f"    - 購買地點: {len(PURCHASE_LOCATIONS)}")
    print(f"    - 食材: {len(INGREDIENTS_DATA)}")
    print(f"    - 訓練項目: {len(EXERCISE_ITEMS)}")
    print(f"    - 瑜珈/拉伸項目: {len(YOGA_STRETCH_ITEMS)}")
    print("=" * 70)

if __name__ == '__main__':
    main()
