# ============================================================================
# 數據庫初始化
# ============================================================================

def create_database():
    """創建或打開數據庫"""
    try:
        conn = sqlite3.connect(str(DB_PATH))
        conn.row_factory = sqlite3.Row
        print(f"✓ 數據庫連接成功: {DB_PATH}")
        return conn
    except sqlite3.Error as e:
        print(f"✗ 數據庫連接失敗: {e}")
        exit(1)

def load_schema(conn):
    """從schema.sql文件加載數據庫架構"""
    try:
        with open(SCHEMA_FILE, 'r', encoding='utf-8') as f:
            schema_sql = f.read()
        
        cursor = conn.cursor()
        cursor.executescript(schema_sql)
        conn.commit()
        print(f"✓ 數據庫架構加載成功")
    except FileNotFoundError:
        print(f"✗ 找不到schema文件: {SCHEMA_FILE}")
        exit(1)
    except sqlite3.Error as e:
        print(f"✗ 架構加載失敗: {e}")
        conn.rollback()
        exit(1)

def record_schema_version(conn):
    """記錄數據庫版本"""
    cursor = conn.cursor()
    cursor.execute("""
        INSERT INTO schema_version (version_number, description, applied_at)
        VALUES (?, ?, ?)
    """, ('1.0', '初始架構 - 2024-08-06', datetime.now()))
    conn.commit()
    print("✓ 記錄架構版本")

