def load_purchase_locations(conn):
    """加載購買地點"""
    cursor = conn.cursor()
    cursor.executemany(
        "INSERT INTO purchase_locations (location_name, description, priority_order) VALUES (?, ?, ?)",
        PURCHASE_LOCATIONS
    )
    conn.commit()
    print(f"✓ 加載 {len(PURCHASE_LOCATIONS)} 個購買地點")

def load_ingredients(conn):
    """加載食材"""
    cursor = conn.cursor()
    cursor.executemany(
        """INSERT INTO ingredient_library 
           (ingredient_name, category, unit, calories_per_100g, protein_per_100g, 
            carbs_per_100g, fat_per_100g, fiber_per_100g, needs_stock_tracking)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)""",
        [(name, cat, unit, cal, pro, carb, fat, fiber, True) 
         for name, cat, unit, cal, pro, carb, fat, fiber in INGREDIENTS_DATA]
    )
    conn.commit()
    print(f"✓ 加載 {len(INGREDIENTS_DATA)} 個食材")

def load_exercise_items(conn):
    """加載訓練項目"""
    cursor = conn.cursor()
    cursor.executemany(
        """INSERT INTO exercise_item_library 
           (item_name, category, description, default_sets, default_reps, muscle_group)
           VALUES (?, ?, ?, ?, ?, ?)""",
        EXERCISE_ITEMS
    )
    conn.commit()
    print(f"✓ 加載 {len(EXERCISE_ITEMS)} 個訓練項目")

def load_yoga_stretch_items(conn):
    """加載瑜珈/拉伸項目"""
    cursor = conn.cursor()
    cursor.executemany(
        """INSERT INTO yoga_stretch_items 
           (type, item_name, duration_min, description, difficulty)
           VALUES (?, ?, ?, ?, ?)""",
        YOGA_STRETCH_ITEMS
    )
    conn.commit()
    print(f"✓ 加載 {len(YOGA_STRETCH_ITEMS)} 個瑜珈/拉伸項目")

def initialize_ingredient_stock(conn):
    """初始化所有食材的庫存"""
    cursor = conn.cursor()
    
    # 先獲取所有食材
    cursor.execute("SELECT id FROM ingredient_library")
    ingredients = cursor.fetchall()
    
    # 為每個食材初始化庫存
    stock_data = [
        (ing['id'], 0, 500, None)  # ingredient_id, current_qty, min_threshold, last_purchased
        for ing in ingredients
    ]
    
    cursor.executemany(
        """INSERT INTO ingredient_stock 
           (ingredient_id, current_quantity_g, min_threshold_g, last_purchased_at)
           VALUES (?, ?, ?, ?)""",
        stock_data
    )
    conn.commit()
    print(f"✓ 初始化 {len(stock_data)} 個食材庫存")

