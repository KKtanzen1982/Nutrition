def _get_or_create_ingredients(db: Session) -> dict:
    existing = {i.ingredient_name: i.id for i in db.query(IngredientLibrary).all()}
    for name, category, unit, cal, protein, carbs, fat, fiber, tracked, threshold in INGREDIENTS:
        if name in existing:
            continue
        ing = IngredientLibrary(
            ingredient_name=name, category=category, unit=unit,
            calories_per_100g=cal, protein_per_100g=protein, carbs_per_100g=carbs,
            fat_per_100g=fat, fiber_per_100g=fiber, needs_stock_tracking=tracked,
            season=INGREDIENT_SEASONS.get(name),
        )
        db.add(ing)
        db.flush()
        existing[name] = ing.id
        if tracked:
            db.add(IngredientStock(ingredient_id=ing.id, current_quantity_g=threshold * 1.5, min_threshold_g=threshold))
    db.commit()
    return existing


def seed_recipes(db: Session):
    ingredient_ids = _get_or_create_ingredients(db)
    existing_recipe_names = {r.recipe_name for r in db.query(Recipe).all()}

    for name, category, base_weight_g, cost_level, is_veg, allergens, ings, steps, carb_source in RECIPES:
        if name in existing_recipe_names:
            continue
        recipe = Recipe(
            recipe_name=name, category=category, base_weight_g=base_weight_g,
            cost_level=cost_level, is_vegetarian=is_veg, allergen_tags=allergens, is_active=True,
            carb_source=carb_source,
        )
        db.add(recipe)
        db.flush()
        totals = {"total_calories_kcal": 0.0, "protein_g": 0.0, "carbs_g": 0.0, "fat_g": 0.0, "fiber_g": 0.0}
        for ing_name, qty in ings:
            ing_id = ingredient_ids[ing_name]
            db.add(RecipeIngredient(recipe_id=recipe.id, ingredient_id=ing_id, quantity_g=qty))
            src = next(i for i in INGREDIENTS if i[0] == ing_name)
            ratio = qty / 100.0
            totals["total_calories_kcal"] += src[3] * ratio
            totals["protein_g"] += src[4] * ratio
            totals["carbs_g"] += src[5] * ratio
            totals["fat_g"] += src[6] * ratio
            totals["fiber_g"] += src[7] * ratio
        for i, step_text in enumerate(steps, start=1):
            db.add(RecipeStep(recipe_id=recipe.id, version=1, step_number=i, step_description=step_text, is_current=True))
        db.add(RecipeNutrition(recipe_id=recipe.id, **{k: round(v, 2) for k, v in totals.items()}))
    db.commit()
